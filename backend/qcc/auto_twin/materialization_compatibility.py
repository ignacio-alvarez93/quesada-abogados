"""Canonical AUTO TWIN materialized-revision runtime compatibility.

Single source of truth for whether an already materialized revision's
generated navigation runtime contract still matches what the CURRENT
code would produce (see navigation_transition_runtime.
AUTO_TWIN_NAVIGATION_RUNTIME_ADAPTER_VERSION, the one existing version
registry for this concern).

Both the governed Discovery materialization reconciler
(automatic_materialization.py's renderer/navigation refresh gate) and
the CRM product path (twin_management_service.py's Open Twin gate)
consult this exact decision. No second version system is introduced.

Generic by construction: nothing here references any particular
managed site, revision id, state id, selector or transition count.
"""

from __future__ import annotations

import json
from pathlib import Path

from .navigation_transition_runtime import (
    AUTO_TWIN_NAVIGATION_RUNTIME_ADAPTER_VERSION,
    AUTO_TWIN_NAVIGATION_RUNTIME_FILENAME,
)


AUTO_TWIN_MATERIALIZATION_COMPATIBLE = "COMPATIBLE"

AUTO_TWIN_MATERIALIZATION_STALE_REGENERATABLE = (
    "STALE_REGENERATABLE"
)

AUTO_TWIN_MATERIALIZATION_INCOMPATIBLE = "INCOMPATIBLE"


def _text(value):
    return str(
        value
        or ""
    ).strip()


def materialized_revision_navigation_runtime_path(
    *,
    materialized_root,
    twin_key,
    revision_id,
):
    return (
        Path(
            materialized_root
        )
        / _text(
            twin_key
        )
        / _text(
            revision_id
        )
        / "runtime"
        / AUTO_TWIN_NAVIGATION_RUNTIME_FILENAME
    )


def evaluate_materialized_revision_compatibility(
    *,
    materialized_root,
    twin_key,
    revision_id,
):
    """Return COMPATIBLE / STALE_REGENERATABLE / INCOMPATIBLE.

    COMPATIBLE: the revision's own navigation runtime manifest was
    generated by the exact adapter version the current code produces.

    STALE_REGENERATABLE: the manifest is missing, unreadable, or was
    generated by an OLDER adapter version -- current local evidence is
    expected to be sufficient to regenerate it.

    INCOMPATIBLE: the manifest declares an adapter version NEWER than
    the current code -- opening or regenerating it is not safe.
    """

    revision_id = _text(
        revision_id
    )

    twin_key = _text(
        twin_key
    )

    if (
        not revision_id
        or not twin_key
    ):
        return (
            AUTO_TWIN_MATERIALIZATION_INCOMPATIBLE
        )

    navigation_path = (
        materialized_revision_navigation_runtime_path(
            materialized_root=materialized_root,
            twin_key=twin_key,
            revision_id=revision_id,
        )
    )

    if not navigation_path.is_file():
        return (
            AUTO_TWIN_MATERIALIZATION_STALE_REGENERATABLE
        )

    try:
        payload = json.loads(
            navigation_path.read_text(
                encoding="utf-8"
            )
        )

        adapter_version = int(
            payload.get(
                "adapter_version"
            )
        )

    except (
        OSError,
        TypeError,
        ValueError,
        json.JSONDecodeError,
    ):
        return (
            AUTO_TWIN_MATERIALIZATION_STALE_REGENERATABLE
        )

    if (
        adapter_version
        == AUTO_TWIN_NAVIGATION_RUNTIME_ADAPTER_VERSION
    ):
        return (
            AUTO_TWIN_MATERIALIZATION_COMPATIBLE
        )

    if (
        adapter_version
        > AUTO_TWIN_NAVIGATION_RUNTIME_ADAPTER_VERSION
    ):
        return (
            AUTO_TWIN_MATERIALIZATION_INCOMPATIBLE
        )

    return (
        AUTO_TWIN_MATERIALIZATION_STALE_REGENERATABLE
    )
